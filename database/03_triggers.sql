-- ----------------------------------------------------------------------------
-- Tabela: audit_log
-- Trilha de auditoria das alteracoes em lancamentos e orcamentos. Sem FK para
-- users de proposito: o historico permanece mesmo apos a exclusao da conta.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    table_name  character varying(63) NOT NULL,
    operation   character varying(6)  NOT NULL,
    record_id   integer               NOT NULL,
    user_id     integer,
    old_data    jsonb,
    new_data    jsonb,
    db_user     character varying(63) NOT NULL DEFAULT current_user,
    executed_at timestamp without time zone NOT NULL DEFAULT timezone('utc', now()),
    CONSTRAINT pk_audit_log PRIMARY KEY (id),
    CONSTRAINT ck_audit_log_operation CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE INDEX IF NOT EXISTS ix_audit_log_table_record ON audit_log (table_name, record_id);
CREATE INDEX IF NOT EXISTS ix_audit_log_user_id ON audit_log (user_id);

COMMENT ON TABLE audit_log IS 'Auditoria de INSERT/UPDATE/DELETE em transactions e budgets (preenchida por trigger).';
COMMENT ON COLUMN audit_log.old_data IS 'Linha antes da alteracao (nulo em INSERT).';
COMMENT ON COLUMN audit_log.new_data IS 'Linha apos a alteracao (nulo em DELETE).';

-- ----------------------------------------------------------------------------
-- Trigger function: fn_set_updated_at
-- Mantem updated_at sempre atualizado, inclusive em alteracoes feitas fora da API.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := timezone('utc', now());
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_categories_updated_at ON categories;
CREATE TRIGGER trg_categories_updated_at
    BEFORE UPDATE ON categories
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_budgets_updated_at ON budgets;
CREATE TRIGGER trg_budgets_updated_at
    BEFORE UPDATE ON budgets
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_transactions_updated_at ON transactions;
CREATE TRIGGER trg_transactions_updated_at
    BEFORE UPDATE ON transactions
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_alerts_updated_at ON alerts;
CREATE TRIGGER trg_alerts_updated_at
    BEFORE UPDATE ON alerts
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ----------------------------------------------------------------------------
-- Trigger function: fn_auditoria
-- Grava a linha antes/depois em audit_log (generica para tabelas com id e user_id).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_log (table_name, operation, record_id, user_id, new_data)
        VALUES (TG_TABLE_NAME, TG_OP, NEW.id, NEW.user_id, to_jsonb(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO audit_log (table_name, operation, record_id, user_id, old_data, new_data)
        VALUES (TG_TABLE_NAME, TG_OP, NEW.id, NEW.user_id, to_jsonb(OLD), to_jsonb(NEW));
        RETURN NEW;
    ELSE
        INSERT INTO audit_log (table_name, operation, record_id, user_id, old_data)
        VALUES (TG_TABLE_NAME, TG_OP, OLD.id, OLD.user_id, to_jsonb(OLD));
        RETURN OLD;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_auditoria_transactions ON transactions;
CREATE TRIGGER trg_auditoria_transactions
    AFTER INSERT OR UPDATE OR DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria();

DROP TRIGGER IF EXISTS trg_auditoria_budgets ON budgets;
CREATE TRIGGER trg_auditoria_budgets
    AFTER INSERT OR UPDATE OR DELETE ON budgets
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria();

-- ----------------------------------------------------------------------------
-- Trigger function: fn_alerta_orcamento
-- Ao registrar ou alterar uma despesa ativa, reavalia o teto da categoria no
-- mes da transacao (sp_verificar_orcamento gera os alertas de 80% e 100%).
-- O AlertService da API usa a mesma chave de deduplicacao, entao os dois
-- caminhos convergem para um unico alerta por categoria/mes/tipo.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_alerta_orcamento()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    CALL sp_verificar_orcamento(
        NEW.user_id,
        NEW.category_id,
        EXTRACT(YEAR FROM NEW.transaction_date)::integer,
        EXTRACT(MONTH FROM NEW.transaction_date)::integer);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_alerta_orcamento ON transactions;
CREATE TRIGGER trg_alerta_orcamento
    AFTER INSERT OR UPDATE OF value, category_id, transaction_date, status, type ON transactions
    FOR EACH ROW
    WHEN (NEW.type = 0 AND NEW.status = 0)
    EXECUTE FUNCTION fn_alerta_orcamento();
