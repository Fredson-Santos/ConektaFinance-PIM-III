-- ----------------------------------------------------------------------------
-- Trigger function: fn_alerta_orcamento
-- Ao registrar ou alterar uma despesa ativa, reavalia o teto da categoria no
-- mes da transacao (sp_verificar_orcamento gera os alertas de 80% e 100%).
-- O AlertService da API usa a mesma chave de deduplicacao, entao os dois
-- caminhos convergem para um unico alerta por categoria/mes/tipo.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_alerta_orcamento()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    CALL sp_verificar_orcamento(
        NEW.user_id,
        NEW.category_id,
        EXTRACT(YEAR FROM NEW.transaction_date)::integer,
        EXTRACT(MONTH FROM NEW.transaction_date)::integer);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_alerta_orcamento ON transactions;
CREATE TRIGGER trg_alerta_orcamento
    AFTER INSERT OR UPDATE OF value, category_id, transaction_date, status, type ON transactions
    FOR EACH ROW
    WHEN (NEW.type = 0 AND NEW.status = 0)
    EXECUTE FUNCTION fn_alerta_orcamento();

