-- ----------------------------------------------------------------------------
-- Function: fn_status_orcamento
-- Situacao do orcamento de uma categoria no mes.
-- Regra (BudgetStatus.EvaluateStatus): sem teto -> noLimit; > 100% -> over;
-- >= 80% -> warn; caso contrario -> ok.
-- Exemplo: SELECT * FROM fn_status_orcamento(1, 3, 2026, 10);
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_status_orcamento(
    p_user_id     integer,
    p_category_id integer,
    p_ano         integer,
    p_mes         integer)
RETURNS TABLE (gasto numeric, limite numeric, percentual numeric, status text)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_inicio timestamp := make_date(p_ano, p_mes, 1);
    v_fim    timestamp := make_date(p_ano, p_mes, 1) + interval '1 month';
BEGIN
    SELECT COALESCE(SUM(t.value), 0)
      INTO gasto
      FROM transactions t
     WHERE t.user_id = p_user_id
       AND t.category_id = p_category_id
       AND t.type = 0          -- despesa
       AND t.status = 0        -- ativa
       AND t.transaction_date >= v_inicio
       AND t.transaction_date <  v_fim;

    SELECT COALESCE(MAX(b.limit_value), 0)
      INTO limite
      FROM budgets b
     WHERE b.user_id = p_user_id
       AND b.category_id = p_category_id
       AND b.period_year = p_ano
       AND b.period_month = p_mes;

    IF limite <= 0 THEN
        percentual := 0;
        status := 'noLimit';
    ELSE
        percentual := round(gasto * 100 / limite, 2);
        status := CASE
            WHEN gasto * 100 / limite > 100 THEN 'over'
            WHEN gasto * 100 / limite >= 80 THEN 'warn'
            ELSE 'ok'
        END;
    END IF;

    RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_status_orcamento(integer, integer, integer, integer)
    IS 'Gasto, teto, percentual e status (ok/warn/over/noLimit) de uma categoria no mes.';

-- ----------------------------------------------------------------------------
-- Procedure: sp_verificar_orcamento
-- Gera ou atualiza o alerta de orcamento da categoria no mes, com a mesma
-- chave de deduplicacao do AlertService:
--   cat:<categoria>:<ano>-<mes>:exceeded  -> type 0 (teto excedido, > 100%)
--   cat:<categoria>:<ano>-<mes>:limit     -> type 1 (atencao, >= 80%)
-- Apenas categorias de despesa (kind = 0) com teto definido geram alerta.
-- Exemplo: CALL sp_verificar_orcamento(1, 3, 2026, 10);
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_verificar_orcamento(
    p_user_id     integer,
    p_category_id integer,
    p_ano         integer,
    p_mes         integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_nome     text;
    v_situacao record;
    v_chave    text;
    v_tipo     integer;
    v_titulo   text;
    v_mensagem text;
BEGIN
    SELECT c.name
      INTO v_nome
      FROM categories c
     WHERE c.id = p_category_id
       AND c.user_id = p_user_id
       AND c.kind = 0;

    IF v_nome IS NULL THEN
        RETURN;
    END IF;

    SELECT * INTO v_situacao FROM fn_status_orcamento(p_user_id, p_category_id, p_ano, p_mes);

    IF v_situacao.status = 'over' THEN
        v_chave    := format('cat:%s:%s-%s:exceeded', p_category_id, p_ano, lpad(p_mes::text, 2, '0'));
        v_tipo     := 0;
        v_titulo   := format('%s acima do teto', v_nome);
        v_mensagem := format('Orcamento excedido em R$ %s. Limite de R$ %s.',
                             to_char(abs(v_situacao.limite - v_situacao.gasto), 'FM9999999999990.00'),
                             to_char(v_situacao.limite, 'FM9999999999990.00'));
    ELSIF v_situacao.status = 'warn' THEN
        v_chave    := format('cat:%s:%s-%s:limit', p_category_id, p_ano, lpad(p_mes::text, 2, '0'));
        v_tipo     := 1;
        v_titulo   := format('%s — %s%% do teto', v_nome, round(v_situacao.percentual));
        v_mensagem := format('Restam R$ %s ate o fechamento do mes.',
                             to_char(greatest(0, v_situacao.limite - v_situacao.gasto), 'FM9999999999990.00'));
    ELSE
        RETURN;
    END IF;

    INSERT INTO alerts (user_id, category_id, type, title, message, is_read, dedup_key)
    VALUES (p_user_id, p_category_id, v_tipo, left(v_titulo, 120), left(v_mensagem, 300), false, v_chave)
    ON CONFLICT (user_id, dedup_key) DO UPDATE
        SET type    = EXCLUDED.type,
            title   = EXCLUDED.title,
            message = EXCLUDED.message;
END;
$$;

COMMENT ON PROCEDURE sp_verificar_orcamento(integer, integer, integer, integer)
    IS 'Cria ou atualiza alertas de 80% e 100% do teto da categoria, sem duplicar.';

-- ----------------------------------------------------------------------------
-- Procedure: sp_fechamento_mensal
-- Consolida receitas, despesas, saldo, uso do teto global e maior categoria
-- de gasto do mes em monthly_closings (insere ou atualiza o periodo).
-- Exemplo: CALL sp_fechamento_mensal(1, 2026, 10);
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_fechamento_mensal(
    p_user_id integer,
    p_ano     integer,
    p_mes     integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_inicio       timestamp;
    v_fim          timestamp;
    v_receitas     numeric(18,2);
    v_despesas     numeric(18,2);
    v_quantidade   integer;
    v_teto         numeric(18,2);
    v_categoria_id integer;
    v_categoria_vl numeric(18,2);
BEGIN
    IF p_mes NOT BETWEEN 1 AND 12 THEN
        RAISE EXCEPTION 'Mes invalido: % (use 1 a 12)', p_mes;
    END IF;

    v_inicio := make_date(p_ano, p_mes, 1);
    v_fim    := v_inicio + interval '1 month';

    SELECT u.monthly_ceiling INTO v_teto FROM users u WHERE u.id = p_user_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Usuario % nao encontrado', p_user_id;
    END IF;

    SELECT COALESCE(SUM(t.value) FILTER (WHERE t.type = 1), 0),
           COALESCE(SUM(t.value) FILTER (WHERE t.type = 0), 0),
           COUNT(*)
      INTO v_receitas, v_despesas, v_quantidade
      FROM transactions t
     WHERE t.user_id = p_user_id
       AND t.status = 0
       AND t.transaction_date >= v_inicio
       AND t.transaction_date <  v_fim;

    SELECT t.category_id, SUM(t.value)
      INTO v_categoria_id, v_categoria_vl
      FROM transactions t
     WHERE t.user_id = p_user_id
       AND t.type = 0
       AND t.status = 0
       AND t.transaction_date >= v_inicio
       AND t.transaction_date <  v_fim
     GROUP BY t.category_id
     ORDER BY SUM(t.value) DESC, t.category_id
     LIMIT 1;

    INSERT INTO monthly_closings (
        user_id, period_year, period_month, total_income, total_expense, balance,
        monthly_ceiling, ceiling_percentage, top_category_id, top_category_total,
        transaction_count, closed_at)
    VALUES (
        p_user_id, p_ano, p_mes, v_receitas, v_despesas, v_receitas - v_despesas,
        v_teto,
        CASE WHEN v_teto > 0 THEN round(v_despesas * 100 / v_teto, 2) END,
        v_categoria_id, COALESCE(v_categoria_vl, 0),
        v_quantidade, now())
    ON CONFLICT (user_id, period_year, period_month) DO UPDATE
        SET total_income       = EXCLUDED.total_income,
            total_expense      = EXCLUDED.total_expense,
            balance            = EXCLUDED.balance,
            monthly_ceiling    = EXCLUDED.monthly_ceiling,
            ceiling_percentage = EXCLUDED.ceiling_percentage,
            top_category_id    = EXCLUDED.top_category_id,
            top_category_total = EXCLUDED.top_category_total,
            transaction_count  = EXCLUDED.transaction_count,
            closed_at          = EXCLUDED.closed_at;
END;
$$;

COMMENT ON PROCEDURE sp_fechamento_mensal(integer, integer, integer)
    IS 'Consolida o mes do usuario em monthly_closings (insere ou atualiza o periodo).';

